"""Pages: privacy policy and terms of use."""
from __future__ import annotations

import streamlit as st

import config
from ui import components

LAST_UPDATED = "15 October 2026"


def _contact() -> str:
    if config.CONTACT_EMAIL:
        return f"the project team at {config.CONTACT_EMAIL}"
    return "the project team named in the README file"


def render_privacy() -> None:
    components.page_header("Privacy policy", f"Last updated {LAST_UPDATED}.")
    st.markdown(f"""
### Who this policy covers
This policy describes how the Football Video Analysis application handles data. The application is a college
project. It is designed to run on your own computer, and this policy is written for that use. A section below
explains what changes if someone hosts a copy on a server.

### What data the application processes
* **Videos you upload or select.** They are read frame by frame to detect and track people.
* **Data derived from the videos.** Box coordinates, tracking IDs, positions, shirt colours, movement statistics,
  coaching insights, the annotated video and PDF reports.
* **Calibration points** you enter on the Pitch calibration page.

The application does not ask for your name, email address, account or payment details, and it does not try to
identify the people who appear in a video. Tracking IDs are arbitrary numbers.

### Where the data is stored
Everything stays in the project folder on the computer that runs the application:
* uploaded videos in `data/uploads/`
* analysis results in `outputs/<analysis name>/`

Nothing is sent to an external server for analysis. No paid or cloud AI service is used.

### Network connections the application makes
* **Model download.** The first time a detection or pose model is used, its weights file is downloaded from the
  official Ultralytics release page on GitHub. Only the file request is sent; no video data.
* **Optional language model.** If you switch on the optional written summary, the computed facts (not the video)
  are sent to an Ollama server at `{config.OLLAMA_URL}`, which by default is on your own computer.
* **Usage statistics are switched off.** The Streamlit framework's usage statistics are disabled in
  `.streamlit/config.toml`.

### Cookies
The interface uses a browser connection to the local server to update the page. It does not set advertising or
tracking cookies.

### How long data is kept and how to delete it
Files are kept until you delete them. To remove all videos and results, delete the contents of `data/uploads/`
and `outputs/`. To remove one analysis, delete its folder inside `outputs/`.

### People who appear in videos
Videos of matches show identifiable people. Only analyse footage you are allowed to use, and do not share
annotated videos or reports of private individuals without their consent.

### If the application is hosted on a server
If a copy is deployed online, uploaded videos and results are stored on that server instead of your computer, and
the operator of that server is responsible for them. The operator must update this policy with their own name,
contact details, storage location, retention period and legal basis before making the site public.

### Children
The application is not directed at children and does not knowingly collect information about them.

### Changes and contact
Changes to this policy are shown on this page with a new date. Questions can be sent to {_contact()}.
""")


