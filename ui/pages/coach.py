"""Page: rule-based coaching insights."""
from __future__ import annotations

import pandas as pd
import streamlit as st

import config
from modules import coaching_insights as ci
from modules.coaching_insights import Insight
from ui import components, state

SECTION_TITLES = {
    "observation": "Measured facts",
    "suggestion": "Suggestions (hypotheses for the coach to check)",
    "data_quality": "Data quality notes",
}


def _render_insights(insights: list[Insight], key: str) -> None:
    for kind in ("data_quality", "observation", "suggestion"):
        items = [i for i in insights if i.kind == kind]
        if not items:
            continue
        st.subheader(SECTION_TITLES[kind])
        for n, ins in enumerate(items):
            with st.container(border=True):
                st.markdown(f"**{ins.title}**")
                st.write(ins.detail)
                if ins.caveat:
                    st.caption(f"Caveat: {ins.caveat}")
                if ins.drill:
                    st.markdown(f"Suggested practice: **{ins.drill['name']}**. {ins.drill['purpose']}")
                with st.expander("Why this was generated"):
                    st.write(f"Rule {ins.rule_id}: {ins.rule}")
                    if ins.evidence:
                        evidence = pd.DataFrame({"value": {k: str(v) for k, v in ins.evidence.items()}})
                        st.dataframe(evidence, width="stretch")


def render() -> None:
    components.page_header(
        "AI coach",
        "Explainable insights generated by transparent rules from the measured data. Each card shows the rule and "
        "the values that triggered it.",
    )
    run = state.current_run()
    if run is None:
        components.no_run_message()
        return
    components.run_caption(run)
    st.caption("The coach does not assess fitness, fatigue, injuries, emotions or tactical effectiveness, and it "
               "does not report passes, shots, goals or possession, because none of these are measured.")
    data = state.bundle(run)
    metrics, zones, overview, spread = data["metrics"], data["zones"], data["overview"], data["spread"]
    space = "pitch" if run.is_calibrated else "image"

    tab_clip, tab_player = st.tabs(["Whole clip", "Single player"])
    with tab_clip:
        team = ci.team_insights(metrics, spread, overview, space)
        _render_insights(team, "team")
    with tab_player:
        stable = state.stable_ids(metrics)
        if not stable:
            st.info("No track was followed long enough for player insights.")
            player_insights = []
        else:
            player = st.selectbox("Track", stable, format_func=lambda i: f"ID {i}", key="coach_player")
            player_insights = ci.player_insights(player, metrics, zones, space, overview["duration_processed_s"])
            _render_insights(player_insights, f"p{player}")

    st.divider()
    st.subheader("Written summary (optional local language model)")
    if config.COACH_LLM_ENABLED:
        st.caption(f"Uses the local Ollama model '{config.OLLAMA_MODEL}'. It only receives the facts shown above.")
        if st.button("Write a summary of the whole clip"):
            try:
                with st.spinner("Waiting for the local model..."):
                    st.write(ci.llm_summary(team, "the whole clip"))
            except RuntimeError as exc:
                st.error(str(exc))
    else:
        st.caption("Disabled. The rule-based insights above work without any language model. To add a written "
                   "summary, install Ollama, run `ollama pull llama3.2`, set the environment variable "
                   "COACH_LLM_ENABLED=1 and restart the app. No paid API is needed.")

    export = pd.concat([ci.insights_dataframe(team, "whole clip")]
                       + ([ci.insights_dataframe(player_insights, f"ID {st.session_state.get('coach_player')}")]
                          if player_insights else []), ignore_index=True)
    st.download_button("Download these insights (CSV)", export.to_csv(index=False).encode("utf-8"),
                       f"{run.run_id}_insights.csv", "text/csv")
