"""Explainable, rule-based coaching insights.

Every insight is generated by a named rule from measured metrics, and keeps
the evidence (metric values and thresholds) that triggered it. Three kinds of
output are kept strictly separate:

* observation  a measured fact from this clip
* suggestion   a hypothesis plus an optional practice drill; it can be wrong
* data_quality a warning that the data is too limited for conclusions

The module never infers fitness, fatigue, injury, emotion or tactical
effectiveness, and it never claims passes, shots, goals or possession,
because none of them are measured.

An optional local language model (Ollama) can rewrite the facts into a short
paragraph. It is disabled by default and receives only the computed facts.
"""
from __future__ import annotations

import json
import math
import urllib.error
import urllib.request
from dataclasses import asdict, dataclass, field

import numpy as np
import pandas as pd

import config

ZONE_MIN_SECONDS = 60.0

DRILLS = {
    "small_sided_games": {
        "name": "Small-sided games (4 v 4 on about 30 x 20 m)",
        "purpose": "More touches and more frequent movement under game-like pressure.",
    },
    "rondo_rotation": {
        "name": "Rondo 4 v 2 with forced rotation",
        "purpose": "Practises constant small movements to offer passing angles.",
    },
    "positional_game": {
        "name": "Positional game in zones (6 v 6 + 3 neutrals)",
        "purpose": "Encourages occupying and moving between different zones of the pitch.",
    },
    "repeated_sprints": {
        "name": "Repeated sprints (6 x 30 m, 25 s recovery)",
        "purpose": "Practises repeated high-speed efforts with short recovery.",
    },
    "acceleration_starts": {
        "name": "Reactive acceleration starts (5 to 10 m, coach signal)",
        "purpose": "Practises the first steps of short accelerations.",
    },
    "unit_shape": {
        "name": "Shadow play for unit shape (back four plus midfield)",
        "purpose": "Practises keeping distances between team-mates while the ball moves.",
    },
    "width_patterns": {
        "name": "Overlap and underlap patterns on both flanks",
        "purpose": "Practises using the full width of the pitch.",
    },
}


@dataclass
class Insight:
    kind: str                      # observation | suggestion | data_quality
    title: str
    detail: str
    rule_id: str
    rule: str                      # why the insight was generated
    evidence: dict = field(default_factory=dict)
    drill: dict | None = None
    caveat: str | None = None

    def to_dict(self) -> dict:
        return asdict(self)


def _fmt(value: float, unit: str, digits: int = 1) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "not available"
    return f"{value:,.{digits}f} {unit}".strip()


def _units(metric_space: str) -> dict:
    if metric_space == "pitch":
        return {"dist": "m", "speed": "m/s", "area": "m²", "label": "calibrated estimate"}
    return {"dist": "px", "speed": "px/s", "area": "px²", "label": "image-space value, not metres"}


def _ratio(value: float, reference: float) -> float | None:
    if reference is None or not np.isfinite(reference) or reference <= 0 or not np.isfinite(value):
        return None
    return value / reference


def player_insights(track_id: int, metrics: pd.DataFrame, zones: pd.DataFrame, metric_space: str,
                    clip_seconds: float) -> list[Insight]:
    """Insights for one tracked player compared with the other stable tracks in the clip."""
    u = _units(metric_space)
    row = metrics.loc[metrics["track_id"] == track_id]
    if row.empty:
        return [Insight("data_quality", "No data for this ID", f"Track ID {track_id} has no recorded positions.",
                        "Q0", "A track must have positions to be analysed.")]
    p = row.iloc[0]
    stable = metrics[metrics["stable"]]
    others = stable[stable["track_id"] != track_id]
    out: list[Insight] = []

    min_visible = max(config.MIN_TRACK_SECONDS * 2.5, 0.2 * clip_seconds)
    if p["visible_s"] < min_visible:
        out.append(Insight(
            "data_quality", "Too little data for suggestions",
            f"ID {track_id} was tracked for {p['visible_s']:.1f} s ({p['visibility_pct']:.0f}% of processed frames). "
            "Only observations are shown.",
            "Q1", f"Suggestions need at least {min_visible:.1f} s of tracking (the larger of 5 s and 20% of the clip).",
            {"visible_s": p["visible_s"], "required_s": round(min_visible, 1)},
        ))
    if len(others) < 3:
        out.append(Insight(
            "data_quality", "Few players to compare with",
            f"Only {len(others)} other stable tracks exist, so comparisons with the group are not made.",
            "Q2", "Comparisons need at least 3 other tracks that were followed for 2 s or more.",
            {"other_stable_tracks": int(len(others))},
        ))
    if p.get("colour_group") == "Unassigned":
        out.append(Insight(
            "data_quality", "Shirt colour matches neither group",
            f"ID {track_id} could not be placed in a colour group. It may be a referee, an assistant referee, a "
            "goalkeeper or a staff member, so player-oriented suggestions may not apply.",
            "Q6", "The track's shirt colour is far from both colour-group centres.",
            {"colour_group": "Unassigned"},
        ))
    enough_time = p["visible_s"] >= min_visible
    can_compare = len(others) >= 3

    # Observations -----------------------------------------------------------
    out.append(Insight(
        "observation", "Tracking coverage",
        f"Tracked from {p['first_seen_s']:.1f} s to {p['last_seen_s']:.1f} s, visible in {p['frames_seen']} processed frames "
        f"({p['visible_s']:.1f} s, {p['visibility_pct']:.0f}% of the processed clip).",
        "O1", "Reported for every track.",
        {"first_seen_s": p["first_seen_s"], "last_seen_s": p["last_seen_s"], "visible_s": p["visible_s"]},
    ))
    out.append(Insight(
        "observation", "Distance and speed",
        f"Distance covered while tracked: {_fmt(p['distance'], u['dist'])}. Average speed while tracked: "
        f"{_fmt(p['avg_speed'], u['speed'], 2)}. Peak speed (95th percentile): {_fmt(p['peak_speed'], u['speed'], 2)}. "
        f"These are {u['label']}s.",
        "O2", "Reported for every track. Positions are smoothed before distances are summed.",
        {"distance": p["distance"], "avg_speed": p["avg_speed"], "peak_speed": p["peak_speed"], "unit": u["dist"]},
    ))
    if metric_space == "pitch":
        out.append(Insight(
            "observation", "High-speed running",
            f"{_fmt(p['high_speed_distance'], 'm')} above {config.HIGH_SPEED_THRESHOLD_MPS} m/s and "
            f"{int(p['sprints']) if np.isfinite(p['sprints']) else 0} sprint(s) above {config.SPRINT_THRESHOLD_MPS} m/s "
            f"lasting at least {config.MIN_BURST_SECONDS:.0f} s.",
            "O3", "Shown only when the video is calibrated to the pitch.",
            {"high_speed_distance_m": p["high_speed_distance"], "sprints": p["sprints"]},
        ))

    zone_row = zones.loc[zones["track_id"] == track_id]
    dominant_third, dominant_share, dominant_channel, channel_share = None, 0.0, None, 0.0
    if not zone_row.empty:
        z = zone_row.iloc[0]
        thirds = {"left third": z["left_third"], "middle third": z["middle_third"], "right third": z["right_third"]}
        channels = {"far channel": z["far_channel"], "central channel": z["central_channel"], "near channel": z["near_channel"]}
        dominant_third, dominant_share = max(thirds.items(), key=lambda kv: kv[1])
        dominant_channel, channel_share = max(channels.items(), key=lambda kv: kv[1])
        frame_of_reference = "of the pitch" if metric_space == "pitch" else "of the camera view"
        out.append(Insight(
            "observation", "Where the player was",
            f"Most time in the {dominant_third} ({dominant_share:.0f}%) and the {dominant_channel} ({channel_share:.0f}%) "
            f"{frame_of_reference}. Thirds: left {thirds['left third']:.0f}%, middle {thirds['middle third']:.0f}%, "
            f"right {thirds['right third']:.0f}%.",
            "O4", "Share of tracked positions in each third and channel.",
            {**{k: float(v) for k, v in thirds.items()}, **{k: float(v) for k, v in channels.items()}},
        ))

    if metric_space != "pitch":
        out.append(Insight(
            "data_quality", "Calibrate the pitch for comparisons and suggestions",
            "Without a pitch calibration, movement is measured in pixels. A player far from the camera moves fewer "
            "pixels than a player near it for the same distance, so comparisons between players and zone-based "
            "suggestions would be misleading. They are enabled after calibration.",
            "Q5", "Comparisons and suggestions are only generated in calibrated (metre) space."))
        return out
    if not (enough_time and can_compare):
        return out

    med_speed = float(others["avg_speed"].median())
    med_area = float(others["area_covered"].median())
    speed_ratio = _ratio(float(p["avg_speed"]), med_speed)
    area_ratio = _ratio(float(p["area_covered"]), med_area)

    if speed_ratio is not None:
        out.append(Insight(
            "observation", "Average speed compared with the group",
            f"Average speed was {speed_ratio * 100:.0f}% of the median of the other {len(others)} stable tracks "
            f"({_fmt(p['avg_speed'], u['speed'], 2)} vs {_fmt(med_speed, u['speed'], 2)}).",
            "O5", "Compared with the median of other stable tracks in the same clip.",
            {"player": p["avg_speed"], "group_median": round(med_speed, 3), "ratio": round(speed_ratio, 2)},
        ))

    # Suggestions --------------------------------------------------------------
    role_caveat = ("This can reflect the player's role or the phase of play in this short clip. "
                   "It is not a measure of fitness or effort.")
    if speed_ratio is not None and speed_ratio < 0.75:
        out.append(Insight(
            "suggestion", "Possible focus: movement intensity",
            "Measured movement speed was clearly lower than most other players in this clip. If the coach wants "
            "more movement from this position, small-sided games raise the number of short movements.",
            "S1", "Average speed below 75% of the group median, with enough tracking time.",
            {"ratio": round(speed_ratio, 2), "threshold": 0.75}, DRILLS["small_sided_games"], role_caveat,
        ))
    if area_ratio is not None and area_ratio < 0.5:
        out.append(Insight(
            "suggestion", "Possible focus: movement off the ball",
            f"The area covered ({_fmt(p['area_covered'], u['area'], 0)}) was less than half of the group median "
            f"({_fmt(med_area, u['area'], 0)}). Rondos with forced rotation practise frequent small repositioning.",
            "S2", "Convex-hull area of positions below 50% of the group median.",
            {"ratio": round(area_ratio, 2), "threshold": 0.5}, DRILLS["rondo_rotation"],
            "Central defenders and goalkeepers usually cover a smaller area by design.",
        ))
    # In short clips the phase of play decides where players are, so zone-based
    # suggestions need at least a minute of tracking.
    long_enough_for_zones = p["visible_s"] >= ZONE_MIN_SECONDS
    if dominant_share >= 70 and long_enough_for_zones:
        out.append(Insight(
            "suggestion", "Possible focus: using more zones",
            f"{dominant_share:.0f}% of the tracked positions were in the {dominant_third}. Positional games in zones "
            "practise moving between areas when the role allows it.",
            "S3", f"One third of the pitch holds at least 70% of the positions, with at least "
                  f"{ZONE_MIN_SECONDS:.0f} s of tracking.",
            {"dominant_third": dominant_third, "share_pct": round(dominant_share, 1), "threshold_pct": 70},
            DRILLS["positional_game"],
            "The clip may only show one phase of play, which naturally keeps players in one area.",
        ))
    if channel_share >= 80 and dominant_channel != "central channel" and long_enough_for_zones:
        out.append(Insight(
            "suggestion", "Possible focus: width and support on the other flank",
            f"{channel_share:.0f}% of positions were in the {dominant_channel}. Overlap and underlap patterns practise "
            "using the full width.",
            "S4", f"One wide channel holds at least 80% of the positions, with at least "
                  f"{ZONE_MIN_SECONDS:.0f} s of tracking.",
            {"channel": dominant_channel, "share_pct": round(channel_share, 1), "threshold_pct": 80},
            DRILLS["width_patterns"], "Full-backs and wingers are often assigned to one flank.",
        ))
    if metric_space == "pitch":
        sprints_group = others["sprints"].fillna(0)
        player_sprints = 0 if not np.isfinite(p["sprints"]) else int(p["sprints"])
        if player_sprints == 0 and (sprints_group > 0).mean() >= 0.5:
            out.append(Insight(
                "suggestion", "Possible focus: short accelerations",
                "No sprint was measured for this player while at least half of the other tracked players sprinted.",
                "S5", "Zero sprints while at least 50% of other stable tracks had one or more.",
                {"player_sprints": 0, "share_of_group_with_sprints": round(float((sprints_group > 0).mean()), 2)},
                DRILLS["acceleration_starts"], "A sprint may simply not have been needed in this clip.",
            ))
        if player_sprints >= 3 and player_sprints >= sprints_group.quantile(0.75):
            out.append(Insight(
                "suggestion", "Strength to maintain: repeated high-speed efforts",
                f"{player_sprints} sprints were measured, among the highest in this clip.",
                "S6", "At least 3 sprints and in the top quarter of the group.",
                {"player_sprints": player_sprints, "group_75th_percentile": float(sprints_group.quantile(0.75))},
                DRILLS["repeated_sprints"], None,
            ))
    return out


def team_insights(metrics: pd.DataFrame, spread: pd.DataFrame, overview: dict, metric_space: str) -> list[Insight]:
    """Clip-level observations and suggestions."""
    u = _units(metric_space)
    out: list[Insight] = []
    stable = metrics[metrics["stable"]] if not metrics.empty else metrics
    if overview["frames_processed"] == 0 or metrics.empty:
        return [Insight("data_quality", "No tracking data", "No players were tracked in this clip.", "Q0",
                        "Insights need tracked players.")]
    if metric_space != "pitch":
        out.append(Insight(
            "data_quality", "Movement values are in pixels",
            "The video is not calibrated to the pitch, so distances and speeds are in image pixels and only "
            "comparable within this clip. Use the Pitch calibration page to get metre estimates.",
            "Q3", "Shown whenever no calibration exists."))
    if overview["scene_cuts"] > 0:
        out.append(Insight(
            "data_quality", "Scene cuts detected",
            f"{overview['scene_cuts']} abrupt change(s) of the image were detected (replays or camera switches). "
            "Positions after a cut may be in a different frame of reference.",
            "Q4", "HSV histogram change above 0.5 between processed frames."))
    out.append(Insight(
        "observation", "Tracking summary",
        f"{overview['unique_track_ids']} track IDs were created and {overview['stable_tracks']} were followed for at least "
        f"{config.MIN_TRACK_SECONDS:.0f} s. On average {overview['mean_tracked_per_frame']} people were tracked per frame. "
        "The number of IDs is usually higher than the number of players because IDs change after occlusions.",
        "T1", "Reported for every clip.",
        {k: overview[k] for k in ("unique_track_ids", "stable_tracks", "mean_tracked_per_frame")},
    ))
    if not stable.empty:
        top = stable.sort_values("distance", ascending=False).head(3)
        listing = ", ".join(f"ID {int(r.track_id)} ({_fmt(r.distance, u['dist'], 0)})" for r in top.itertuples())
        out.append(Insight(
            "observation", "Most distance while tracked",
            f"Highest distances among stable tracks: {listing}. Tracks that were visible longer naturally cover more distance.",
            "T2", "Top three stable tracks by distance.", {"top": listing}))

    if not spread.empty:
        summary = spread.groupby("colour_group")["spread"].mean()
        if len(summary) == 2:
            g1, g2 = float(summary.get("Group 1", np.nan)), float(summary.get("Group 2", np.nan))
            out.append(Insight(
                "observation", "Distance between team-mates (colour groups)",
                f"Average distance of players to their group centre: Group 1 {_fmt(g1, u['dist'])}, "
                f"Group 2 {_fmt(g2, u['dist'])}. Groups are formed by shirt colour and are experimental.",
                "T3", "Mean distance to the group centroid over frames with at least 3 players of the group.",
                {"group_1": round(g1, 2), "group_2": round(g2, 2)}))
            wider = "Group 1" if g1 > g2 else "Group 2"
            ratio = max(g1, g2) / max(1e-6, min(g1, g2))
            if ratio >= 1.3 and metric_space == "pitch":
                out.append(Insight(
                    "suggestion", f"Possible focus for {wider}: compactness",
                    f"{wider}'s players were on average {ratio:.1f} times further from their group centre. If a more "
                    "compact block is wanted, shadow play for unit shape practises distances between team-mates.",
                    "S7", "One group's mean spread is at least 1.3 times the other's.",
                    {"ratio": round(ratio, 2), "threshold": 1.3}, DRILLS["unit_shape"],
                    "Spread depends on whether the group was attacking or defending, which is not measured.",
                ))
    return out


def insights_dataframe(insights: list[Insight], subject: str) -> pd.DataFrame:
    rows = []
    for ins in insights:
        rows.append({
            "subject": subject, "kind": ins.kind, "title": ins.title, "detail": ins.detail,
            "rule_id": ins.rule_id, "rule": ins.rule, "evidence": json.dumps(ins.evidence, default=str),
            "drill": ins.drill["name"] if ins.drill else "", "caveat": ins.caveat or "",
        })
    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Optional local language model (Ollama). Disabled unless COACH_LLM_ENABLED=1.
# ---------------------------------------------------------------------------
def llm_summary(insights: list[Insight], subject: str, timeout: float = 60.0) -> str:
    facts = [{"kind": i.kind, "title": i.title, "detail": i.detail} for i in insights]
    prompt = (
        "You are assisting a football coach. Write a short neutral summary (max 120 words) of the facts below "
        f"about {subject}. Use only these facts. Keep observations and suggestions clearly separate. Do not "
        "mention fitness, fatigue, injury, emotions, passes, shots, goals or possession.\n\n"
        + json.dumps(facts, indent=1)
    )
    body = json.dumps({"model": config.OLLAMA_MODEL, "prompt": prompt, "stream": False}).encode("utf-8")
    request = urllib.request.Request(f"{config.OLLAMA_URL.rstrip('/')}/api/generate", data=body,
                                     headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return json.loads(response.read().decode("utf-8")).get("response", "").strip()
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"The local language model at {config.OLLAMA_URL} did not respond: {exc}") from exc
